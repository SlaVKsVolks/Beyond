class RepositoryRustSafetyTests(unittest.TestCase):
    def test_prepare_has_unconditional_package_enforcement(self) -> None:
        root = Path(__file__).resolve().parents[1]
        issues = audit(root, WORKSPACES)
        manifest = str(Path('crates/horizon-prepare/Cargo.toml'))
        relevant = [
            issue for issue in issues
            if issue.startswith((f'{manifest}:', 'Cargo.toml: Cargo metadata failed:',
                                 'manifest discovery/parsing failed:', 'TOML parser unavailable;'))
        ]
        self.assertEqual([], relevant, relevant)

    def test_standalone_console_cargo_package_is_enforced(self) -> None:
        root = Path(__file__).resolve().parents[1]
        manifest = Path('launcher/tests/support/console-probe/Cargo.toml')
        self.assertIn(manifest, WORKSPACES)
        issues = audit(root, WORKSPACES)
        console_issues = [issue for issue in issues if 'console-probe' in issue]
        self.assertEqual(console_issues, [], console_issues)

    def test_launcher_has_unconditional_package_enforcement(self) -> None:
        root = Path(__file__).resolve().parents[1]
        workspaces = {
            Path('Cargo.toml'),
            Path('launcher/Cargo.toml'),
            Path('launcher/tests/support/console-probe/Cargo.toml'),
            Path('crates/horizon-telemetry-server/Cargo.toml'),
            Path('crates/horizon-mod-registry/Cargo.toml'),
        }
        issues = audit(root, workspaces)
        launcher = str(Path('launcher/Cargo.toml'))
        launcher_issues = [
            issue for issue in issues
            if issue.startswith((f'{launcher}:', 'manifest discovery/parsing failed:',
                                 'TOML parser unavailable;', f'expected workspace missing: {launcher}'))
        ]
        self.assertEqual([], launcher_issues)


class RustSafetyTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'project'
        self.root.mkdir()
        (self.root / 'src').mkdir()
        (self.root / 'src' / 'lib.rs').write_text('pub fn value() -> u8 { 1 }\n', encoding='utf-8')
        (self.root / 'Cargo.lock').write_text('# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "fixture"\nversion = "0.1.0"\n', encoding='utf-8')
        self.manifest('[lints.rust]\nunsafe_code = "forbid"\n')

    def manifest(self, lint: str) -> None:
        (self.root / 'Cargo.toml').write_text('[package]\nname = "fixture"\nversion = "0.1.0"\nedition = "2021"\n\n[workspace]\n\n' + lint, encoding='utf-8')

    def test_forbid_package_covers_all_cargo_targets(self) -> None:
        (self.root / 'build.rs').write_text('fn main() {}\n', encoding='utf-8')
        (self.root / 'examples').mkdir()
        (self.root / 'examples' / 'demo.rs').write_text('fn main() {}\n', encoding='utf-8')
        self.assertEqual([], audit(self.root, {Path('Cargo.toml')}))

    def test_missing_forbid_fails_even_if_target_root_has_attribute(self) -> None:
        self.manifest('')
        (self.root / 'src' / 'lib.rs').write_text('#![forbid(unsafe_code)]\npub fn value() {}\n', encoding='utf-8')
        self.assertTrue(any('unsafe_code' in issue for issue in audit(self.root, {Path('Cargo.toml')})))

    def test_unknown_workspace_fails_closed(self) -> None:
        (self.root / 'extra').mkdir()
        (self.root / 'extra' / 'Cargo.toml').write_text('[workspace]\n', encoding='utf-8')
        self.assertTrue(any('workspace' in issue for issue in audit(self.root, {Path('Cargo.toml')})))

    def test_malformed_manifest_fails_closed(self) -> None:
        self.manifest('[lints.rust\n')
        self.assertTrue(any('parsing failed' in issue for issue in audit(self.root, {Path('Cargo.toml')})))

    def test_inherited_forbid_is_required(self) -> None:
        self.manifest('[lints]\nworkspace = true\n')
        self.assertTrue(any('metadata failed' in issue for issue in audit(self.root, {Path('Cargo.toml')})))

    def test_workspace_forbid_covers_inheriting_package(self) -> None:
        self.manifest('[workspace.lints.rust]\nunsafe_code = "forbid"\n\n[lints]\nworkspace = true\n')
        self.assertEqual([], audit(self.root, {Path('Cargo.toml')}))

    def test_nested_third_party_cannot_hide_a_workspace(self) -> None:
        hidden = self.root / 'src' / 'third_party'
        hidden.mkdir()
        (hidden / 'Cargo.toml').write_text('[workspace]\n', encoding='utf-8')
        self.assertTrue(any('unexpected workspace' in issue for issue in audit(self.root, {Path('Cargo.toml')})))

    def test_main_fails_when_direct_input_auditor_reports_blocker(self) -> None:
        helper = ModuleType('tools.rust_direct_inputs')
        def report(_root: Path) -> list[str]:
            return ['console probe contains unsafe']
        helper.audit_direct_inputs = report
        output = io.StringIO()
        with patch.dict(sys.modules, {'tools.rust_direct_inputs': helper}), patch('tools.check_rust_safety.audit', return_value=[]), redirect_stdout(output):
            self.assertEqual(1, main())
        self.assertIn('console probe contains unsafe', output.getvalue())

    def test_missing_toml_parsers_fail_audit_without_aborting_import(self) -> None:
        real_import = builtins.__import__
        def without_toml(name: str, *args: object, **kwargs: object) -> object:
            if name in {'tomllib', 'tomli'}:
                raise ModuleNotFoundError(name)
            return real_import(name, *args, **kwargs)
        spec = importlib.util.spec_from_file_location('isolated_safety_checker', Path(__file__).resolve().parents[1] / 'tools/check_rust_safety.py')
        assert spec and spec.loader
        module = importlib.util.module_from_spec(spec)
        with patch('builtins.__import__', side_effect=without_toml):
            spec.loader.exec_module(module)
        self.assertTrue(any('tomli' in issue for issue in module.audit(self.root, {Path('Cargo.toml')})))

    def test_excluded_directory_reparse_point_is_rejected(self) -> None:
        excluded = self.root / 'target'
        excluded.mkdir()
        original = Path.lstat
        def marked(path: Path, *args: object, **kwargs: object) -> object:
            value = original(path, *args, **kwargs)
            if path == excluded:
                return SimpleNamespace(st_mode=value.st_mode, st_file_attributes=0x400)
            return value
        with patch.object(Path, 'lstat', marked):
            issues = audit(self.root, {Path('Cargo.toml')})
        self.assertTrue(any('reparse' in issue and 'target' in issue for issue in issues), issues)

    def test_external_cargo_example_source_is_rejected(self) -> None:
        outside = Path(self.temp.name) / 'outside.rs'
        outside.write_text('fn main() {}\n', encoding='utf-8')
        with (self.root / 'Cargo.toml').open('a', encoding='utf-8') as manifest:
            manifest.write('\n[[example]]\nname = "outside"\npath = "../outside.rs"\n')
        issues = audit(self.root, {Path('Cargo.toml')})
        self.assertTrue(any('target source' in issue and 'outside' in issue for issue in issues), issues)

    def test_external_path_dependency_is_rejected(self) -> None:
        outside = Path(self.temp.name) / 'dependency'
        (outside / 'src').mkdir(parents=True)
        (outside / 'Cargo.toml').write_text('[package]\nname="external"\nversion="0.1.0"\nedition="2021"\n', encoding='utf-8')
        (outside / 'src' / 'lib.rs').write_text('pub fn safe() {}\n', encoding='utf-8')
        with (self.root / 'Cargo.toml').open('a', encoding='utf-8') as manifest:
            manifest.write('\n[dev-dependencies]\nexternal = { path = "../dependency" }\n')
        issues = audit(self.root, {Path('Cargo.toml')})
        self.assertTrue(any('dependency' in issue and 'outside' in issue for issue in issues), issues)

    def test_external_build_script_is_rejected(self) -> None:
        (Path(self.temp.name) / 'outside.rs').write_text('fn main() {}\n', encoding='utf-8')
        path = self.root / 'Cargo.toml'
        path.write_text(path.read_text(encoding='utf-8').replace('edition = "2021"', 'edition = "2021"\nbuild = "../outside.rs"'), encoding='utf-8')
        issues = audit(self.root, {Path('Cargo.toml')})
        self.assertTrue(any('target source' in issue and 'outside' in issue for issue in issues), issues)

    def test_each_external_dependency_kind_is_rejected(self) -> None:
        outside = Path(self.temp.name) / 'dependency'
        (outside / 'src').mkdir(parents=True)
        (outside / 'Cargo.toml').write_text('[package]\nname="external"\nversion="0.1.0"\nedition="2021"\n', encoding='utf-8')
        (outside / 'src' / 'lib.rs').write_text('pub fn safe() {}\n', encoding='utf-8')
        for section in ('dependencies', 'build-dependencies', 'dev-dependencies', "target.'cfg(windows)'.dependencies"):
            with self.subTest(section=section):
                self.manifest('[lints.rust]\nunsafe_code = "forbid"\n\n[' + section + ']\nexternal = { path = "../dependency" }\n')
                issues = audit(self.root, {Path('Cargo.toml')})
                self.assertTrue(any('dependency' in issue and 'outside' in issue for issue in issues), issues)

    def test_in_tree_local_dependency_is_accepted(self) -> None:
        dependency = self.root / 'dependency'
        (dependency / 'src').mkdir(parents=True)
        (dependency / 'Cargo.toml').write_text('[package]\nname="internal"\nversion="0.1.0"\nedition="2021"\n[lints.rust]\nunsafe_code="forbid"\n', encoding='utf-8')
        (dependency / 'src' / 'lib.rs').write_text('pub fn safe() {}\n', encoding='utf-8')
        self.manifest('[lints.rust]\nunsafe_code = "forbid"\n\n[dependencies]\ninternal = { path = "dependency" }\n')
        self.assertEqual([], audit(self.root, {Path('Cargo.toml')}))

    def test_file_reparse_point_is_rejected(self) -> None:
        source = self.root / 'src' / 'lib.rs'
        original = Path.lstat
        def marked(path: Path, *args: object, **kwargs: object) -> object:
            value = original(path, *args, **kwargs)
            if path == source:
                return SimpleNamespace(st_mode=value.st_mode, st_file_attributes=0x400)
            return value
        with patch.object(Path, 'lstat', marked):
            issues = audit(self.root, {Path('Cargo.toml')})
        self.assertTrue(any('reparse' in issue and 'lib.rs' in issue for issue in issues), issues)

    def test_target_path_rejects_reparse_ancestor(self) -> None:
        directory = self.root / 'target' / 'generated'
        directory.mkdir(parents=True)
        source = directory / 'fixture.rs'
        source.write_text('fn main() {}\n', encoding='utf-8')
        original = Path.lstat
        def marked(path: Path, *args: object, **kwargs: object) -> object:
            value = original(path, *args, **kwargs)
            if path == directory:
                return SimpleNamespace(st_mode=value.st_mode, st_file_attributes=0x400)
            return value
        with patch.object(Path, 'lstat', marked):
            with self.assertRaisesRegex(ValueError, 'reparse'):
                contained_path(self.root, str(source), 'target source')

    def test_registry_dependency_without_path_is_accepted(self) -> None:
        command = ['cargo', 'metadata', '--offline', '--locked', '--no-deps', '--format-version', '1', '--manifest-path', str(self.root / 'Cargo.toml')]
        result = subprocess.run(command, cwd=self.root, capture_output=True, text=True, check=True)
        metadata = json.loads(result.stdout)
        metadata['packages'][0]['dependencies'].append({
            'name': 'registry-fixture', 'source': 'registry+https://example.invalid/index',
            'req': '^1', 'kind': None, 'rename': None, 'optional': False,
            'uses_default_features': True, 'features': [], 'target': None, 'registry': None,
        })
        result.stdout = json.dumps(metadata)
        with patch('tools.check_rust_safety.subprocess.run', return_value=result):
            self.assertEqual([], audit(self.root, {Path('Cargo.toml')}))

    def test_dependency_without_source_or_path_fails_closed(self) -> None:
        command = ['cargo', 'metadata', '--offline', '--locked', '--no-deps', '--format-version', '1', '--manifest-path', str(self.root / 'Cargo.toml')]
        result = subprocess.run(command, cwd=self.root, capture_output=True, text=True, check=True)
        metadata = json.loads(result.stdout)
        metadata['packages'][0]['dependencies'].append({'name': 'malformed', 'source': None})
        result.stdout = json.dumps(metadata)
        with patch('tools.check_rust_safety.subprocess.run', return_value=result):
            issues = audit(self.root, {Path('Cargo.toml')})
        self.assertTrue(any('dependency' in issue and 'source' in issue for issue in issues), issues)

